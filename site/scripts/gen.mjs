// Build-time manifests so the app no longer loads every page and every icon up front.
// 1. Route and nav metadata from each page's `export const route/nav` (pages load lazily).
// 2. Only the lucide icons the code actually names.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve('src/app');
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const files = walk(root).filter((f) => /\.(jsx?|astro)$/.test(f) && !f.includes('.generated.'));

function grabObject(src, name) {
  const i = src.indexOf(`export const ${name} =`);
  if (i === -1) return null;
  let j = src.indexOf('{', i), depth = 0, k = j;
  for (; k < src.length; k++) {
    if (src[k] === '{') depth++;
    else if (src[k] === '}' && --depth === 0) break;
  }
  return src.slice(j, k + 1);
}

const entries = [];
for (const f of files.filter((f) => f.includes(`${path.sep}pages${path.sep}`) && f.endsWith('.jsx'))) {
  const src = fs.readFileSync(f, 'utf8');
  const route = grabObject(src, 'route');
  const nav = grabObject(src, 'nav');
  if (!route && !nav) continue;
  const key = '/src/app/' + path.relative(root, f).split(path.sep).join('/');
  entries.push(`  { file: ${JSON.stringify(key)}, route: ${route ?? 'null'}, nav: ${nav ?? 'null'} },`);
}
fs.writeFileSync(path.join(root, 'router/manifest.generated.js'), `// Generated by scripts/gen.mjs. Do not edit.\nexport const PAGES = [\n${entries.join('\n')}\n];\n`);

const lucide = await import('lucide-react');
const valid = new Set(Object.keys(lucide).filter((k) => /^[A-Z]/.test(k) && !k.endsWith('Icon') && !k.startsWith('Lucide')));
const pascal = (s) => s.split('-').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('');
const used = new Set();
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8');
  for (const m of src.matchAll(/['"`]([A-Z][A-Za-z0-9]*)['"`]/g)) if (valid.has(m[1])) used.add(m[1]);
  for (const m of src.matchAll(/['"`]([a-z][a-z0-9]*(?:-[a-z0-9]+)+)['"`]/g)) if (valid.has(pascal(m[1]))) used.add(pascal(m[1]));
}
const names = [...used].sort();
fs.writeFileSync(path.join(root, 'components/icons.generated.js'),
  `// Generated by scripts/gen.mjs. Do not edit.\nimport { ${names.join(', ')} } from 'lucide-react';\nexport const ICONS = { ${names.join(', ')} };\n`);
console.log(`routes: ${entries.length}, icons: ${names.length}`);
